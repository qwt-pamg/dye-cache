#: 内置 FAQ（FR-9.6）——README §5 的常见问题 + V1.1 新增问题
FAQ_TEXT = """【这张图和上次不一样？】
每张图都由 run 目录里的 run_params.yaml 参数决定。想复现旧图：
「⑤ 染料库」页选染料 → 载入最新 run 参数 → 重新分析。

【为什么图是糊的/分辨率不够投稿？】
「开始分析」默认只出**预览图**（低 dpi，为了快）。
确认无误后点右上角「定稿出图」，得到 600 dpi 的 png（不再出 PDF）。

【改了出图参数却没反应？】
1) 确认改的是「出图预设 / 高级…」里的参数；
2) 参数改动只在**下一次**分析或「定稿出图」时生效；
3) config.yaml 里打错键名会有红字提示（不再静默忽略）。

【Output 目录里为什么多了染料文件夹？】
V1.1 起结果按染料归档：runs/<染料名>/<时间戳>/。
染料名来自 `预分析整定 → 染料命名`（不填则按组名首字段自动推导）。
老的 runs/run_* 目录不会被移动，只读浏览。

【文件名不规范 / 时间是错的怎么办？】
用 `预分析整定 → 时间工作表`（类 Origin 表格）：双击 t(生效) 直接改，
或选中多行用「批量设置…」（常量 / 起点+步长 / 平移 / 锚点插值）。
改动只写进 run 目录的 time_overrides.yaml，**不会改动你的原始文件**。

【某几个文件被自动剔除了，为什么？】
鼠标悬停在灰色行上可以看到人话解释与建议。
最常见的是：波长轴与其他文件不一致、吸光度饱和、文件读取失败。

【没有 Φ_Δ 结果？】
多为缺少参比（ref）组或探针波长处无有效数据；结果表与日志区会给出中文说明。

【config.yaml 改坏了怎么办？】
程序会备份为 config.yaml.bad.<时间戳> 并回退默认值，弹窗会告诉你原因；
菜单「工具 → 恢复上一份配置」可一键回滚（另保留最近 5 份快照）。

【原始数据会被修改吗？】
不会。程序对输入文件**只读**；所有整定只存在于本次会话与 run 目录的记录中。
"""
